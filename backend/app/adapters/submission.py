"""External-service adapter boundary.

No government integration exists in this prototype. The only configured
submission adapter is a clearly labelled simulator. A production adapter must
implement the same interface and return a verified acknowledgement before the
application may display an official receipt.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Protocol

from app.config import get_settings
from app.db import utcnow


@dataclass
class SubmissionResult:
    accepted: bool
    adapter: str
    is_simulated: bool
    receipt_number: str | None
    issued_at: datetime
    verified: bool
    verification_evidence: str
    message: str
    raw: dict[str, Any] = field(default_factory=dict)


class SubmissionAdapter(Protocol):
    name: str

    def submit(self, *, draft_ref: str, payload: dict[str, Any], idempotency_key: str) -> SubmissionResult: ...


class SimulatedSubmissionAdapter:
    """Explicitly labelled simulator. Never implies a real government filing."""

    name = "SIMULATED_DEMO_ADAPTER"

    def submit(self, *, draft_ref: str, payload: dict[str, Any], idempotency_key: str) -> SubmissionResult:
        digest = hashlib.sha256(f"{draft_ref}:{idempotency_key}".encode()).hexdigest()[:8].upper()
        now = utcnow()
        return SubmissionResult(
            accepted=True,
            adapter=self.name,
            is_simulated=True,
            receipt_number=f"SIM-{digest}",
            issued_at=now,
            verified=True,
            verification_evidence="Simulated acknowledgement matched the idempotency key. No government system was contacted.",
            message=(
                "SIMULATED SUBMISSION. This receipt was generated by the demo adapter and is not a government receipt."
            ),
            raw={
                "receipt_number": f"SIM-{digest}",
                "is_simulated": True,
                "idempotency_key": idempotency_key,
                "issued_at": now.isoformat(),
                "disclaimer": "No official government integration exists in this prototype.",
            },
        )


class UnavailableSubmissionAdapter:
    """Used outside demo mode when no authorised integration is configured."""

    name = "UNAVAILABLE_NO_AUTHORISED_INTEGRATION"

    def submit(self, *, draft_ref: str, payload: dict[str, Any], idempotency_key: str) -> SubmissionResult:
        return SubmissionResult(
            accepted=False,
            adapter=self.name,
            is_simulated=False,
            receipt_number=None,
            issued_at=utcnow(),
            verified=False,
            verification_evidence="No adapter configured",
            message="No authorised submission integration is configured. Nothing was sent.",
            raw={"configured": False},
        )


def get_submission_adapter() -> SubmissionAdapter:
    settings = get_settings()
    if settings.demo_mode and settings.allow_simulated_submission:
        return SimulatedSubmissionAdapter()
    return UnavailableSubmissionAdapter()
